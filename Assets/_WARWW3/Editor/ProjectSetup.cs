using System;
using System.IO;
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEditor.Localization;
using UnityEngine;
using UnityEngine.Localization;
using UnityEngine.Localization.Settings;
using UnityEngine.Localization.Tables;
using UnityEngine.Rendering;
using UnityEngine.Rendering.Universal;
using UnityEditor.SceneManagement;

namespace WarWW3.Editor
{
    [InitializeOnLoad]
    public static class ProjectSetup
    {
        const string Root = "Assets/_WARWW3/";
        const string Marker = Root + "Settings/setup-v1.txt";
        static ProjectSetup()
        {
            EditorApplication.delayCall += () =>
            {
                if (!Application.isBatchMode && !EditorApplication.isPlayingOrWillChangePlaymode && !File.Exists(Marker)) Prepare();
            };
        }
        [MenuItem("WAR WW3/Prepare prototype assets")]
        public static void Prepare()
        {
            Directory.CreateDirectory(Root + "Settings"); Directory.CreateDirectory(Root + "Localization/Tables");
            Directory.CreateDirectory(Root + "Resources/Materials"); Directory.CreateDirectory(Root + "Resources/Units"); Directory.CreateDirectory(Root + "Resources/Prefabs");
            AssetDatabase.Refresh();
            var pipeline = AssetDatabase.LoadAssetAtPath<UniversalRenderPipelineAsset>(Root + "Settings/WarWW3-URP.asset");
            if (pipeline == null)
            {
                var renderer = ScriptableObject.CreateInstance<UniversalRendererData>();
                AssetDatabase.CreateAsset(renderer, Root + "Settings/WarWW3-Renderer.asset");
                pipeline = UniversalRenderPipelineAsset.Create(renderer);
                pipeline.supportsHDR = false; pipeline.msaaSampleCount = 1; pipeline.renderScale = 1; pipeline.shadowDistance = 100; pipeline.useSRPBatcher = true;
                AssetDatabase.CreateAsset(pipeline, Root + "Settings/WarWW3-URP.asset");
            }
            GraphicsSettings.defaultRenderPipeline = pipeline;
            for (int level = 0; level < QualitySettings.names.Length; level++) QualitySettings.SetRenderPipelineAssetAt(level, pipeline);
            CreateMaterial("Lit", "Universal Render Pipeline/Lit"); CreateMaterial("Unlit", "Universal Render Pipeline/Unlit");
            PrepareLocalization(); PrepareUnit("Bulwark", "bulwark", false); PrepareUnit("Kestrel", "kestrel", true);
            PlayerSettings.companyName = "WAR WW3 Project"; PlayerSettings.productName = "WAR WW3";
            PlayerSettings.defaultScreenWidth = 1600; PlayerSettings.defaultScreenHeight = 900; PlayerSettings.resizableWindow = true;
            PlayerSettings.fullScreenMode = FullScreenMode.FullScreenWindow; PlayerSettings.runInBackground = true;
            PlayerSettings.SetUseDefaultGraphicsAPIs(BuildTarget.StandaloneWindows64, false);
            PlayerSettings.SetGraphicsAPIs(BuildTarget.StandaloneWindows64, new[] { GraphicsDeviceType.Direct3D11 });
            var serialized = new SerializedObject(AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/ProjectSettings.asset")[0]);
            var input = serialized.FindProperty("activeInputHandler"); if (input != null) { input.intValue = 0; serialized.ApplyModifiedPropertiesWithoutUndo(); }
            EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(Root + "Scenes/MainMenu.unity", true), new EditorBuildSettingsScene(Root + "Scenes/Battlefield.unity", true) };
            AssetDatabase.SaveAssets();
            File.WriteAllText(Marker, "Prototype setup schema 1. Generated by WAR WW3/Prepare prototype assets.\n");
            AssetDatabase.Refresh(); Debug.Log("WAR WW3 assets prepared. Open MainMenu and press Play.");
        }
        static void CreateMaterial(string name, string shader)
        {
            string path = Root + "Resources/Materials/" + name + ".mat";
            if (AssetDatabase.LoadAssetAtPath<Material>(path) != null) return;
            var mat = new Material(Shader.Find(shader)); mat.enableInstancing = true; AssetDatabase.CreateAsset(mat, path);
        }
        static void PrepareLocalization()
        {
            string settingsPath = Root + "Localization/LocalizationSettings.asset";
            var settings = AssetDatabase.LoadAssetAtPath<LocalizationSettings>(settingsPath);
            if (settings == null) { settings = ScriptableObject.CreateInstance<LocalizationSettings>(); AssetDatabase.CreateAsset(settings, settingsPath); }
            LocalizationEditorSettings.ActiveLocalizationSettings = settings;
            var locales = new List<Locale>();
            foreach (string code in new[] { "en-US", "th-TH" })
            {
                string path = Root + "Localization/" + code + ".asset";
                var locale = AssetDatabase.LoadAssetAtPath<Locale>(path);
                if (locale == null) { locale = Locale.CreateLocale(code); AssetDatabase.CreateAsset(locale, path); }
                LocalizationEditorSettings.AddLocale(locale); locales.Add(locale);
            }
            var collection = LocalizationEditorSettings.GetStringTableCollection("UI") ?? LocalizationEditorSettings.CreateStringTableCollection("UI", Root + "Localization/Tables", locales);
            var catalog = JsonUtility.FromJson<TranslationCatalog>(Resources.Load<TextAsset>("Localization/UI").text);
            foreach (var table in collection.StringTables)
            {
                foreach (var row in catalog.entries) if (table.GetEntry(row.key) == null) table.AddEntry(row.key, table.LocaleIdentifier.Code == "th-TH" ? row.th : row.en);
                collection.SetPreloadTableFlag(table, true); EditorUtility.SetDirty(table);
            }
            EditorUtility.SetDirty(collection.SharedData); EditorUtility.SetDirty(collection); EditorUtility.SetDirty(settings);
        }
        static void PrepareUnit(string name, string id, bool scout)
        {
            string path = Root + "Resources/Units/" + name + ".asset";
            var definition = AssetDatabase.LoadAssetAtPath<UnitDefinition>(path);
            if (definition == null)
            {
                definition = ScriptableObject.CreateInstance<UnitDefinition>(); definition.unitId = id; definition.nameKey = "unit." + id;
                var stats = scout ? Core.PrototypeScenario.DefaultScout() : Core.PrototypeScenario.DefaultTank();
                definition.health = stats.Health; definition.armor = stats.Armor; definition.damage = stats.Damage; definition.speed = stats.Speed; definition.range = stats.Range; definition.fireInterval = stats.FireInterval;
                AssetDatabase.CreateAsset(definition, path);
            }
            if (definition.visualPrefab != null) return;
            string prefabPath = Root + "Resources/Prefabs/" + name + ".prefab";
            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
            if (prefab == null)
            {
                var root = new GameObject(name); var lods = new List<LOD>();
                for (int i = 0; i < 2; i++)
                {
                    var model = AssetDatabase.LoadAssetAtPath<GameObject>(Root + "Models/" + name + "_LOD" + i + ".fbx");
                    if (model == null) continue;
                    var instance = UnityEngine.Object.Instantiate(model, root.transform); instance.name = name + "_LOD" + i;
                    lods.Add(new LOD(i == 0 ? 0.12f : 0.025f, instance.GetComponentsInChildren<Renderer>()));
                }
                if (lods.Count == 0) { UnityEngine.Object.DestroyImmediate(root); throw new InvalidOperationException("Generate Blender FBX assets before preparation."); }
                var group = root.AddComponent<LODGroup>(); group.SetLODs(lods.ToArray()); group.RecalculateBounds();
                prefab = PrefabUtility.SaveAsPrefabAsset(root, prefabPath); UnityEngine.Object.DestroyImmediate(root);
            }
            definition.visualPrefab = prefab; EditorUtility.SetDirty(definition);
        }
        public static void BuildWindows()
        {
            Prepare(); Directory.CreateDirectory("Builds/Windows");
            var report = BuildPipeline.BuildPlayer(new BuildPlayerOptions { scenes = new[] { Root + "Scenes/MainMenu.unity", Root + "Scenes/Battlefield.unity" }, locationPathName = "Builds/Windows/WARWW3.exe", target = BuildTarget.StandaloneWindows64, options = BuildOptions.Development });
            if (report.summary.result != BuildResult.Succeeded) throw new Exception("Player build failed: " + report.summary.result);
        }
        [MenuItem("WAR WW3/Open main menu")]
        public static void OpenMenu() { EditorSceneManager.OpenScene(Root + "Scenes/MainMenu.unity"); }
    }
}
